declare(strict_types=1);

namespace Piwik\Updates;

use Piwik\Updater;
use Piwik\Updater\Migration;
use Piwik\Updater\Migration\Factory as MigrationFactory;
use Piwik\Updates;

/**
 * Activates the new bundled DebugView plugin. Activating it runs its install(), which creates the
 * debugview_raw_request table, so upgraded installations end up with the same schema as new ones.
 */
class Updates_6_1_0_b3 extends Updates
{
    private MigrationFactory $migration;

    public function __construct(MigrationFactory $factory)
    {
        $this->migration = $factory;
    }

    /**
     * @return Migration[]
     */
    public function getMigrations(Updater $updater): array
    {
        return [
            $this->migration->plugin->activate('DebugView'),
        ];
    }

    public function doUpdate(Updater $updater): void
    {
        $updater->executeMigrations(__FILE__, $this->getMigrations($updater));
    }
}
