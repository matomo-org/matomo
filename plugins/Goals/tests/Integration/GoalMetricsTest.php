declare(strict_types=1);

namespace Piwik\Plugins\Goals\tests\Integration;

use Piwik\Cache;
use Piwik\Columns\MetricsList;
use Piwik\Plugins\Goals\API as GoalsApi;
use Piwik\Tests\Framework\Fixture;
use Piwik\Tests\Framework\TestCase\IntegrationTestCase;

/**
 * @group Goals
 * @group Plugins
 * @group GoalMetricsTest
 */
class GoalMetricsTest extends IntegrationTestCase
{
    /**
     * @var int
     */
    private $idGoal;

    public function setUp(): void
    {
        parent::setUp();

        Fixture::createSuperUser(true);
        Fixture::loadAllTranslations();

        $idSite = Fixture::createWebsite('2015-01-01 00:00:00');
        $this->idGoal = GoalsApi::getInstance()->addGoal($idSite, 'Thank you page', 'url', 'thank-you', 'contains');

        $_GET['idSite'] = $idSite;
        Cache::getTransientCache()->flushAll();
    }

    public function tearDown(): void
    {
        unset($_GET['idSite']);
        Cache::getTransientCache()->flushAll();
        Fixture::resetTranslations();

        parent::tearDown();
    }

    /**
     * @dataProvider getGoalMetricsToTest
     */
    public function testGoalMetricsUseTranslatedNamesAndDocumentation(
        string $metricSuffix,
        string $expectedName,
        string $expectedDocumentation
    ): void {
        $metric = MetricsList::get()->getMetric('goal_' . $this->idGoal . '_' . $metricSuffix);

        self::assertNotEmpty($metric);
        self::assertSame(sprintf($expectedName, $this->idGoal), $metric->getTranslatedName());
        self::assertSame($expectedDocumentation, $metric->getDocumentation());
    }

    public function getGoalMetricsToTest(): iterable
    {
        yield 'conversions' => [
            'conversion',
            'Conversions goal "Thank you page" (ID %d)',
            'The number of times this goal was converted.',
        ];

        yield 'revenue' => [
            'revenue',
            'Revenue goal "Thank you page" (ID %d)',
            'The amount of revenue that was generated by converting this goal.',
        ];

        yield 'days to conversion' => [
            'daystoconversion',
            'Days to conversion goal "Thank you page" (ID %d)',
            'The number of days it took a visitor to convert this goal.',
        ];

        yield 'visits to conversion' => [
            'visitstoconversion',
            'Visits to conversion goal "Thank you page" (ID %d)',
            'The number of visits it took a visitor to convert this goal.',
        ];
    }
}
